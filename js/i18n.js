const LANG_KEY = 'store_lang';

export const i18n = {
  current: localStorage.getItem(LANG_KEY) || 'ru',

  t(key) {
    return translations[this.current][key] || key;
  },

  toggle() {
    this.current = this.current === 'ru' ? 'en' : 'ru';
    localStorage.setItem(LANG_KEY, this.current);
    window.location.reload();
  },

  getLang() {
    return this.current;
  }
};
